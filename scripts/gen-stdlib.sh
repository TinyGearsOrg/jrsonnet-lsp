#!/bin/sh
# Regenerates src/stdlib/table.rs: the members of jrsonnet's `std` and each function's
# parameters, read from the evaluator itself (`FuncVal::params()`) at the pinned jrsonnet rev.
# Builds jrsonnet, which takes a few minutes the first time. Set GEN_DIR to keep the build
# around between runs.
set -eu

cd "$(dirname "$0")/.."
./scripts/setup-jrsonnet.sh

# Build outside the repo: inside it, cargo would pick up our .cargo/config.toml, which patches
# the very crates being built.
gen=${GEN_DIR:-${TMPDIR:-/tmp}/jsonnet-lsp-gen}
rm -rf "$gen/src"
mkdir -p "$gen"
cp -r .jrsonnet "$gen/src"
mkdir -p "$gen/src/crates/jrsonnet-stdlib/examples"
cat > "$gen/src/crates/jrsonnet-stdlib/examples/dump_sigs.rs" <<'RUST'
use jrsonnet_evaluator::{State, Val, trace::PathResolver};
use jrsonnet_stdlib::ContextInitializer;

fn main() {
	let mut s = State::builder();
	s.context_initializer(ContextInitializer::new(PathResolver::Absolute));
	let s = s.build();
	let names = s
		.evaluate_snippet(
			"names".to_owned(),
			r#"std.join("\n", [n for n in std.objectFieldsAll(std) if !std.startsWith(n, "__")])"#,
		)
		.expect("list std members");
	let Val::Str(names) = names else {
		panic!("expected a string")
	};
	for name in names.to_string().lines() {
		match s
			.evaluate_snippet("member".to_owned(), format!("std.{name}"))
			.expect("evaluate std member")
		{
			Val::Func(f) => println!("{name}\tfn\t{}", f.params()),
			_ => println!("{name}\tvalue\t"),
		}
	}
}
RUST
(cd "$gen/src" && CARGO_TARGET_DIR="$gen/target" cargo run -q -p jrsonnet-stdlib --example dump_sigs) > "$gen/sigs.tsv"

tab=$(printf '\t')
{
	echo '//! Generated by scripts/gen-stdlib.sh; do not edit.'
	echo
	echo 'use super::Member;'
	echo
	echo 'pub const MEMBERS: &[Member] = &['
	while IFS="$tab" read -r name kind sig; do
		if [ "$kind" = value ]; then
			printf '\tMember { name: "%s", params: None },\n' "$name"
			continue
		fi
		# `(a, b = <default>)` -> "a", "b = …"
		inner=$(printf '%s' "$sig" | sed 's/^(//; s/)$//; s|/\*no arguments\*/||; s/<default>/…/g')
		list=""
		if [ -n "$inner" ]; then
			list=$(printf '%s' "$inner" | sed 's/, /\n/g' | sed 's/.*/"&"/' | paste -sd, - | sed 's/,/, /g')
		fi
		printf '\tMember { name: "%s", params: Some(&[%s]) },\n' "$name" "$list"
	done < "$gen/sigs.tsv"
	echo '];'
} > src/stdlib/table.rs
cargo fmt
echo "wrote src/stdlib/table.rs ($(grep -c 'Member {' src/stdlib/table.rs) members)"
